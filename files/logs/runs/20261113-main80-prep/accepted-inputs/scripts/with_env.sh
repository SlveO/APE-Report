#!/usr/bin/env bash
set -euo pipefail
APE_WORKSPACE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
APE_RUNTIME="$APE_WORKSPACE/.runtime"
mkdir -p "$APE_RUNTIME"/{home,tmp,cache,config,data,state,run,hf,torch,cuda,triton,matplotlib,browser}
chmod 700 "$APE_RUNTIME/run"
unset PYTHONHOME
export HOME="$APE_RUNTIME/home"
export TMPDIR="$APE_RUNTIME/tmp" TMP="$APE_RUNTIME/tmp" TEMP="$APE_RUNTIME/tmp"
export XDG_CACHE_HOME="$APE_RUNTIME/cache" XDG_CONFIG_HOME="$APE_RUNTIME/config" XDG_DATA_HOME="$APE_RUNTIME/data"
export XDG_STATE_HOME="$APE_RUNTIME/state" XDG_RUNTIME_DIR="$APE_RUNTIME/run"
export HF_HOME="$APE_RUNTIME/hf" HF_HUB_CACHE="$APE_RUNTIME/hf/hub" HF_DATASETS_CACHE="$APE_RUNTIME/hf/datasets"
export HF_MODULES_CACHE="$APE_RUNTIME/hf/modules" TRANSFORMERS_CACHE="$APE_RUNTIME/hf/hub"
export TORCH_HOME="$APE_RUNTIME/torch" TORCH_EXTENSIONS_DIR="$APE_RUNTIME/torch/extensions"
export CUDA_CACHE_PATH="$APE_RUNTIME/cuda" TRITON_CACHE_DIR="$APE_RUNTIME/triton" MPLCONFIGDIR="$APE_RUNTIME/matplotlib"
export PYTHONNOUSERSITE=1 PYTHONDONTWRITEBYTECODE=1 TOKENIZERS_PARALLELISM=false
export PYTHONPATH="$APE_WORKSPACE/.overlays/main80-scoring:$APE_WORKSPACE/.overlays/core-tf44:$APE_WORKSPACE/APE"
export CUDA_VISIBLE_DEVICES=0
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_DATASETS_OFFLINE=1
export HF_HUB_DISABLE_TELEMETRY=1 HF_HUB_DISABLE_XET=1 DO_NOT_TRACK=1
export PIP_DISABLE_PIP_VERSION_CHECK=1 PIP_NO_CACHE_DIR=1
cd "$APE_WORKSPACE"
exec "$@"
